"""Autoresponders and per-mailbox spam rules as one panel-managed Sieve script per mailbox.

Design (see also dovecot_dropin()):
- Each mailbox gets /home/vmail/<domain>/<local>/sieve-managed/managed.sieve, generated by the
  panel from settings.json next to it. Dovecot runs it through `sieve_before`, so it runs before
  the mailbox's personal script (the one Roundcube edits over managesieve) and never touches it.
  Roundcube can neither see nor overwrite the managed script: managesieve only manages the
  personal sieve directory (/home/vmail/<domain>/<local>/sieve).
- Pigeonhole runs the next script of the sequence only while a keep is in effect. The managed
  script therefore files or discards mail only when it means it (blocked sender, spam), and the
  user's own filters still run for everything else, including mail it auto-replied to.
- Fixed order inside the managed script (MANAGED_ORDER): block list, spam rules (allow-listed
  senders skip them), autoresponder. So the autoresponder never answers blocked senders or spam.

Everything here is pure (no I/O) so the web side and the root side validate the same way.
"""
import datetime
import json
import re

VMAIL_ROOT = '/home/vmail'
VMAIL_USER = 'vmail'
MANAGED_DIR = 'sieve-managed'
SCRIPT_NAME = 'managed.sieve'
BINARY_NAME = 'managed.svbin'
SETTINGS_NAME = 'settings.json'
DROPIN_PATH = '/etc/dovecot/conf.d/95-indianscloud-sieve.conf'
MAILSCANNER_CONF = '/etc/MailScanner/MailScanner.conf'
NAMESPACE_PREFIX = 'INBOX.'      # live namespace: prefix "INBOX.", separator "."
MANAGED_ORDER = ('block', 'spam', 'vacation')

MAX_SUBJECT = 200
MAX_BODY = 8000
MAX_ALIASES = 20
MAX_LIST = 300
MIN_DAYS, MAX_DAYS = 1, 30
MIN_THRESHOLD, MAX_THRESHOLD = 1, 50
ACTIONS = ('junk', 'discard')

DOMAIN_RE = re.compile(r'^(?=.{3,253}\Z)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,61}[a-z0-9]\Z')
LOCAL_RE = re.compile(r'^[A-Za-z0-9](?:[A-Za-z0-9._+-]{0,62}[A-Za-z0-9_+-])?\Z')
DATE_RE = re.compile(r'^\d{4}-\d{2}-\d{2}\Z')
FOLDER_RE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9 _-]{0,59}\Z')
HEADER_RE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9-]{0,99}\Z')

DEFAULT_VACATION = {'enabled': False, 'subject': '', 'body': '', 'start': '', 'end': '', 'days': 7,
                    'addresses': []}
DEFAULT_SPAM = {'move_spam': False, 'folder': 'Junk', 'threshold': None, 'threshold_action': 'junk',
                'allow': [], 'block': [], 'block_action': 'discard'}

# What MailScanner adds on this server unless MailScanner.conf says otherwise (read at run time).
DEFAULT_HEADERS = {
    'flags': [['X-Spam-Status', 'Yes*'],     # MailScanner "Spam Actions = deliver header ..."
              ['X-Spam-Flag', 'YES'],         # SpamAssassin's own header (spamd / spamass-milter)
              ['X-Spam', 'Yes']],             # Rspamd (milter_headers), when Rspamd is in use
    'score_header': 'X-yoursite-MailScanner-SpamScore',
    'score_char': 's',
    'score_numeric': False,
    'required': 6.0,
    'high': 10.0,
    'high_actions': 'store',
}


class SieveError(ValueError):
    pass


# ----------------------------------------------------------------------------- input validation

def clean_email(value):
    if not isinstance(value, str) or len(value) > 80 or value.count('@') != 1:
        raise SieveError('Invalid email address.')
    local, domain = value.strip().split('@')
    domain = domain.lower()
    if not LOCAL_RE.match(local) or '..' in local or not DOMAIN_RE.match(domain) or '..' in domain:
        raise SieveError('Invalid email address: %s' % value[:80])
    return '%s@%s' % (local, domain)


def mailbox_dir(email):
    """/home/vmail/<domain>/<local>, the CyberPanel layout (e_users.mail = maildir:<this>/Maildir)."""
    local, domain = clean_email(email).split('@')
    return '%s/%s/%s' % (VMAIL_ROOT, domain, local)


def _bool(value, name):
    if not isinstance(value, bool):
        raise SieveError('%s must be true or false.' % name)
    return value


def _int(value, name, low, high):
    if isinstance(value, str) and re.match(r'^\d{1,3}\Z', value.strip()):
        value = int(value.strip())
    if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
        raise SieveError('%s must be a whole number from %d to %d.' % (name, low, high))
    return value


def clean_date(value, name):
    if value in (None, ''):
        return ''
    if not isinstance(value, str) or not DATE_RE.match(value):
        raise SieveError('%s must be a date (YYYY-MM-DD).' % name)
    try:
        datetime.date(*map(int, value.split('-')))
    except ValueError:
        raise SieveError('%s is not a valid date.' % name)
    return value


def _text(value, name, limit, multiline):
    if value is None:
        value = ''
    if not isinstance(value, str):
        raise SieveError('%s must be text.' % name)
    value = value.replace('\r\n', '\n').replace('\r', '\n')
    if multiline:
        value = ''.join(c for c in value if c in '\n\t' or ord(c) >= 32 and ord(c) != 127)
    else:
        value = ''.join(c if ord(c) >= 32 and ord(c) != 127 else ' ' for c in value).strip()
    if len(value) > limit:
        raise SieveError('%s is longer than %d characters.' % (name, limit))
    return value


def clean_vacation(data, today=None):
    """Validate autoresponder settings. `today` (a date) refuses an end date already in the past."""
    data = data if isinstance(data, dict) else {}
    out = dict(DEFAULT_VACATION)
    out['enabled'] = _bool(data.get('enabled', False), 'Autoresponder on/off')
    out['subject'] = _text(data.get('subject'), 'Subject', MAX_SUBJECT, False)
    out['body'] = _text(data.get('body'), 'Message', MAX_BODY, True)
    out['start'] = clean_date(data.get('start'), 'Start date')
    out['end'] = clean_date(data.get('end'), 'End date')
    out['days'] = _int(data.get('days', 7), 'Reply interval (days)', MIN_DAYS, MAX_DAYS)
    aliases = data.get('addresses') or []
    if isinstance(aliases, str):
        aliases = [a for a in re.split(r'[\s,;]+', aliases) if a]
    if not isinstance(aliases, list) or len(aliases) > MAX_ALIASES:
        raise SieveError('Up to %d other addresses.' % MAX_ALIASES)
    seen = []
    for alias in aliases:
        alias = clean_email(alias).lower()
        if alias not in seen:
            seen.append(alias)
    out['addresses'] = seen
    if out['start'] and out['end'] and out['end'] < out['start']:
        raise SieveError('The end date is before the start date.')
    if out['enabled']:
        if not out['body'].strip():
            raise SieveError('Write the reply message.')
        if today is not None and out['end'] and out['end'] < today.isoformat():
            raise SieveError('The end date is in the past.')
    return out


def clean_sender(value):
    """A list entry: user@example.com, or a whole domain as @example.com / example.com."""
    if not isinstance(value, str):
        raise SieveError('Invalid sender.')
    value = value.strip()
    if '@' in value and not value.startswith('@'):
        return clean_email(value).lower()
    domain = value.lstrip('@').lower()
    if not DOMAIN_RE.match(domain) or '..' in domain:
        raise SieveError('Invalid sender or domain: %s' % value[:80])
    return '@' + domain


def _senders(values, name):
    if isinstance(values, str):
        values = [v for v in re.split(r'[\s,;]+', values) if v]
    if values is None:
        values = []
    if not isinstance(values, list) or len(values) > MAX_LIST:
        raise SieveError('%s: up to %d entries.' % (name, MAX_LIST))
    out = []
    for value in values:
        entry = clean_sender(value)
        if entry not in out:
            out.append(entry)
    return out


def clean_spam(data):
    data = data if isinstance(data, dict) else {}
    out = dict(DEFAULT_SPAM)
    out['move_spam'] = _bool(data.get('move_spam', False), 'Move spam')
    folder = data.get('folder') or 'Junk'
    if not isinstance(folder, str) or not FOLDER_RE.match(folder) or folder.upper() == 'INBOX':
        raise SieveError('Folder: letters, digits, spaces, _ and -, up to 60 characters.')
    out['folder'] = folder
    threshold = data.get('threshold')
    out['threshold'] = None if threshold in (None, '') else _int(threshold, 'Spam score threshold',
                                                                 MIN_THRESHOLD, MAX_THRESHOLD)
    for key in ('threshold_action', 'block_action'):
        value = data.get(key, DEFAULT_SPAM[key])
        if value not in ACTIONS:
            raise SieveError('Action must be junk or discard.')
        out[key] = value
    out['allow'] = _senders(data.get('allow'), 'Allow list')
    out['block'] = _senders(data.get('block'), 'Block list')
    both = set(out['allow']) & set(out['block'])
    if both:
        raise SieveError('On both lists: %s' % ', '.join(sorted(both)))
    return out


def clean_settings(data, today=None):
    data = data if isinstance(data, dict) else {}
    return {'vacation': clean_vacation(data.get('vacation'), today), 'spam': clean_spam(data.get('spam'))}


def load_settings(text):
    """Stored settings (settings.json), validated again; defaults when missing or damaged."""
    try:
        return clean_settings(json.loads(text))
    except (TypeError, ValueError):
        return {'vacation': dict(DEFAULT_VACATION), 'spam': dict(DEFAULT_SPAM)}


# ----------------------------------------------------------------------------- MailScanner headers

def _conf_values(text):
    values = {}
    for line in (text or '').splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        values[key.strip().lower()] = value.strip()
    return values


def mailscanner_headers(text):
    """Which headers MailScanner adds, from MailScanner.conf (None/'' text: the defaults)."""
    result = json.loads(json.dumps(DEFAULT_HEADERS))
    if not text:
        return result
    values = _conf_values(text)

    def expand(value):
        return re.sub(r'%([a-z-]+)%', lambda m: values.get('%%%s%%' % m.group(1), m.group(0)), value)

    score = expand(values.get('spam score header', 'X-%org-name%-MailScanner-SpamScore:')).rstrip(':').strip()
    if HEADER_RE.match(score):
        result['score_header'] = score
    char = values.get('spam score character', 's')
    result['score_char'] = char[:1] if char[:1] and char[:1] not in '\\"*?' else 's'
    result['score_numeric'] = values.get('spamscore number instead of stars', 'no').lower() in ('yes', '1')
    for key, name in (('required', 'required spamassassin score'), ('high', 'high spamassassin score')):
        try:
            result[key] = float(values.get(name, result[key]))
        except ValueError:
            pass
    result['high_actions'] = values.get('high scoring spam actions', result['high_actions'])
    match = re.search(r'header\s+"([A-Za-z0-9-]+):\s*([^"]*)"', values.get('spam actions', ''))
    if match and HEADER_RE.match(match.group(1)):
        flag = [match.group(1), match.group(2).strip() + '*']
        result['flags'] = [flag] + [f for f in result['flags'] if f[0].lower() != flag[0].lower()]
    return result


# ----------------------------------------------------------------------------- Sieve rendering

def quote(value):
    """A Sieve quoted string (RFC 5228 2.4.2): backslash and double quote escaped; newlines kept."""
    value = str(value).replace('\x00', '')
    return '"%s"' % value.replace('\\', '\\\\').replace('"', '\\"')


def string_list(values):
    values = list(values)
    return quote(values[0]) if len(values) == 1 else '[%s]' % ', '.join(quote(v) for v in values)


def sender_test(entries):
    """A test matching the From address against addresses and @domains; None for an empty list."""
    addresses = [e for e in entries if not e.startswith('@')]
    domains = [e[1:] for e in entries if e.startswith('@')]
    tests = []
    if addresses:
        tests.append('address :all :is "from" %s' % string_list(addresses))
    if domains:
        tests.append('address :domain :is "from" %s' % string_list(domains))
    if not tests:
        return None
    return tests[0] if len(tests) == 1 else 'anyof(%s)' % ', '.join(tests)


def score_test(headers, threshold):
    """True when the spam score is at least `threshold` (MailScanner star or number header)."""
    name = headers['score_header']
    if headers.get('score_numeric'):
        return ('allof(header :value "ge" :comparator "i;ascii-numeric" %s %s, not header :matches %s "-*")'
                % (quote(name), quote(str(threshold)), quote(name)))
    return 'header :matches %s %s' % (quote(name), quote(headers['score_char'] * threshold + '*'))


def flag_test(headers):
    tests = ['header :matches %s %s' % (quote(name), quote(value)) for name, value in headers['flags']]
    return tests[0] if len(tests) == 1 else 'anyof(%s)' % ', '.join(tests)


def _action(kind, folder):
    if kind == 'discard':
        return ['discard;', 'stop;']
    return ['fileinto :create %s;' % quote(NAMESPACE_PREFIX + folder), 'stop;']


def _indent(lines, level=1):
    return ['    ' * level + line for line in lines]


def _block(test, body):
    return ['if %s {' % test] + _indent(body) + ['}']


def render(settings, email, headers=None):
    """The managed Sieve script for one mailbox, or None when no rule is on."""
    headers = headers or DEFAULT_HEADERS
    vacation, spam = settings['vacation'], settings['spam']
    sections = {}
    requires = set()
    block = sender_test(spam['block'])
    if block:
        sections['block'] = ['# 1. Block list: never delivered to the inbox, never answered.'] + \
            _block(block, _action(spam['block_action'], spam['folder']))
        if spam['block_action'] == 'junk':
            requires.update(('fileinto', 'mailbox'))
    spam_lines = []
    if spam['threshold'] is not None and spam['threshold_action'] == 'discard':
        spam_lines += _block(score_test(headers, spam['threshold']), _action('discard', spam['folder']))
    junk_tests = []
    if spam['move_spam']:
        junk_tests.append(flag_test(headers))
    if spam['threshold'] is not None and spam['threshold_action'] == 'junk':
        junk_tests.append(score_test(headers, spam['threshold']))
    if junk_tests:
        test = junk_tests[0] if len(junk_tests) == 1 else 'anyof(%s)' % ', '.join(junk_tests)
        spam_lines += _block(test, _action('junk', spam['folder']))
        requires.update(('fileinto', 'mailbox'))
    if spam_lines:
        if any('ascii-numeric' in line for line in spam_lines):
            requires.update(('relational', 'comparator-i;ascii-numeric'))
        allow = sender_test(spam['allow'])
        head = ['# 2. Spam rules (MailScanner/SpamAssassin headers).']
        if allow:
            sections['spam'] = head + ['# Allow-listed senders skip them.'] + _block('not ' + allow, spam_lines)
        else:
            sections['spam'] = head + spam_lines
    if vacation['enabled'] and vacation['body'].strip():
        requires.add('vacation')
        arguments = ':days %d' % vacation['days']
        if vacation['subject']:
            arguments += ' :subject %s' % quote(vacation['subject'])
        if vacation['addresses']:
            arguments += ' :addresses %s' % string_list(vacation['addresses'])
        reply = ['vacation %s' % arguments, '    %s;' % quote(vacation['body'])]
        bounds = []
        if vacation['start']:
            bounds.append('currentdate :value "ge" "date" %s' % quote(vacation['start']))
        if vacation['end']:
            bounds.append('currentdate :value "le" "date" %s' % quote(vacation['end']))
        if bounds:
            requires.update(('date', 'relational'))
            test = bounds[0] if len(bounds) == 1 else 'allof(%s)' % ', '.join(bounds)
            reply = _block(test, reply)
        sections['vacation'] = ['# 3. Autoresponder (keeps the message, so your own filters still run).'] + reply
    if not sections:
        return None
    order = ['fileinto', 'mailbox', 'relational', 'comparator-i;ascii-numeric', 'date', 'vacation']
    lines = ['# IndiansCloud managed mail rules for %s.' % clean_email(email).replace('\n', ''),
             '# Generated by the panel from settings.json; edits here are overwritten.',
             '# Runs before your own filters (sieve_before).',
             'require %s;' % string_list([r for r in order if r in requires]), '']
    for name in MANAGED_ORDER:
        if name in sections:
            lines += sections[name] + ['']
    return '\n'.join(lines)


def vacation_active(vacation, today):
    """Whether the autoresponder answers today (for the page)."""
    if not vacation['enabled']:
        return False
    day = today.isoformat()
    return (not vacation['start'] or vacation['start'] <= day) and (not vacation['end'] or day <= vacation['end'])


# ----------------------------------------------------------------------------- Dovecot

def dovecot_problems(doveconf_text, sievec_present, dovecot_conf_text=''):
    """What stops the managed scripts from running, from `doveconf -n` output (read-only)."""
    text = doveconf_text or ''
    problems = []
    if not sievec_present:
        problems.append('Pigeonhole (Dovecot Sieve) is not installed: no sievec. For the GhettoForge dovecot23 '
                        'packages on this server that is dovecot23-pigeonhole of the same version.')
    lda = re.search(r'^protocol lda \{(.*?)^\}', text, re.S | re.M)
    lda_plugins = re.search(r'^\s*mail_plugins\s*=\s*(.*)$', lda.group(1), re.M) if lda else None
    global_plugins = re.search(r'^mail_plugins\s*=\s*(.*)$', text, re.M)
    plugins = (lda_plugins or global_plugins)
    if not plugins or 'sieve' not in plugins.group(1).split():
        problems.append('The sieve plugin is not in mail_plugins for protocol lda (deliver).')
    if not re.search(r'^\s*sieve_before\d*\s*=\s*.*%s/%s' % (re.escape(MANAGED_DIR), re.escape(SCRIPT_NAME)), text, re.M):
        problems.append('sieve_before does not point at the panel-managed script.')
    if not re.search(r'^mail_home\s*=', text, re.M):
        problems.append('Dovecot has no home directory for mailboxes (needed for the vacation reply log).')
    extensions = re.search(r'^\s*sieve_extensions\s*=\s*(.*)$', text, re.M)
    if extensions and 'vacation' in extensions.group(1) and '-vacation' in extensions.group(1).split():
        problems.append('The vacation extension is disabled (sieve_extensions = -vacation).')
    if dovecot_conf_text and DROPIN_PATH not in dovecot_conf_text and not re.search(
            r'^\s*!include(_try)?\s+.*conf\.d/\*\.conf', dovecot_conf_text, re.M):
        problems.append('dovecot.conf does not include %s.' % DROPIN_PATH)
    return problems


def dovecot_dropin():
    """The Dovecot drop-in the managed scripts need. Shown to the administrator; never written here."""
    return '''# %(path)s
# IndiansCloud: panel-managed autoresponders and spam rules (Pigeonhole Sieve).
# Requires Pigeonhole for this Dovecot (dovecot23-pigeonhole, same version as dovecot23).
# This server's dovecot.conf does not read conf.d, so also append to /etc/dovecot/dovecot.conf:
#   !include_try %(path)s

# The SQL userdb returns no home; Sieve keeps the vacation reply log (.dovecot.lda-dupes)
# and the personal scripts there. Same layout as the mail= paths in e_users.
mail_home = %(root)s/%%d/%%n

# managesieve for Roundcube (local only).
protocols = $protocols sieve
service managesieve-login {
  inet_listener sieve {
    address = 127.0.0.1
    port = 4190
  }
}

protocol lda {
  mail_plugins = $mail_plugins sieve
}

plugin {
  # The mailbox's own filters (Roundcube managesieve).
  sieve = file:%(root)s/%%d/%%n/sieve;active=%(root)s/%%d/%%n/.dovecot.sieve
  # Panel-managed rules run first: block list, spam rules, autoresponder. A mailbox without
  # managed rules has no such file.
  sieve_before = %(root)s/%%d/%%n/%(dir)s/%(script)s
  sieve_vacation_min_period = 1d
  sieve_vacation_max_period = 30d
}
''' % {'path': DROPIN_PATH, 'root': VMAIL_ROOT, 'dir': MANAGED_DIR, 'script': SCRIPT_NAME}
