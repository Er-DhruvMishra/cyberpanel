def _context_block(scope):
    lines = ['context %s {' % scope.uri]
    if scope.location:
        lines.append('  location                %s' % scope.location)
    lines.append('  allowBrowse             1')
    if scope.index_files:
        lines.append('  indexFiles              %s' % ', '.join(scope.index_files))
    if scope.autoindex:
        lines.append('  autoIndex               1')
    if scope.auth_ready():
        lines.append('  realm                   %s' % scope.auth['realm'])
        if scope.auth.get('name'):
            lines.append('  authName                %s' % scope.auth['name'].replace('"', ''))
        lines.append('  required                %s' % scope.auth['require'])
    access = scope.access()
    if access:
        allow, deny = access
        lines += ['  accessControl  {']
        if allow:
            lines.append('    allow                 %s' % ', '.join(allow))
        if deny:
            lines.append('    deny                  %s' % ', '.join(deny))
        lines.append('  }')
    if scope.headers:
        lines.append('  extraHeaders            <<<END_extraHeaders')
        lines += scope.headers
        lines.append('  END_extraHeaders')
    if scope.uri != '/' or scope.is_regex:
        if scope.php:
            lines += ['  phpIniOverride  {'] + ['    ' + p for p in scope.php] + ['  }']
        if scope.expires_active is not None:
            lines.append('  enableExpires           %d' % (1 if scope.expires_active else 0))
        if scope.expires_default:
            lines.append('  expiresDefault          %s' % scope.expires_default)
        if scope.expires_by_type:
            lines.append('  expiresByType           %s' % ', '.join('%s=%s' % kv for kv in sorted(scope.expires_by_type.items())))
    lines += ['  rewrite  {', '    enable                  1', '    autoLoadHtaccess        1', '  }', '}']
    return '\n'.join(lines)


PRESERVED = '# preserved from vhost.conf'
FROM_HTACCESS = '# from .htaccess'


def render_vhost_block(result, existing_php=()):
    """The managed text inserted into vhost.conf (between MARK_BEGIN / MARK_END).

    The vhost's own phpIniOverride lines are kept (marked PRESERVED) because OpenLiteSpeed
    allows a single vhost-level phpIniOverride block; .htaccess settings follow and win.
    """
    parts = [MARK_BEGIN]
    if existing_php or result.vhost['php']:
        parts.append('phpIniOverride  {\n%s\n}' % '\n'.join(
            ([PRESERVED] + list(existing_php) if existing_php else []) + [FROM_HTACCESS] + result.vhost['php']))
    for code, target in sorted(result.vhost['errorpages'].items()):
        parts.append('errorpage %s {\n  url                     %s\n}' % (code, target))
    if result.vhost['expires']:
        active, default, by_type = result.vhost['expires']
        block = ['expires  {', '  enableExpires           %d' % (1 if active else 0)]
        if default:
            block.append('  expiresDefault          %s' % default)
        if by_type:
            block.append('  expiresByType           %s' % ', '.join('%s=%s' % kv for kv in sorted(by_type.items())))
        parts.append('\n'.join(block + ['}']))
    for realm, userfile in sorted(result.realms.items()):
        parts.append('realm %s {\n  userDB  {\n    location              %s\n  }\n}' % (realm, userfile))
    for scope in result.contexts:
        parts.append(_context_block(scope))
    parts.append(MARK_END)
    return '\n\n'.join(parts) + '\n'


def strip_managed(text, begin=MARK_BEGIN, end=MARK_END):
    pattern = re.compile(r'\n?' + re.escape(begin) + r'.*?' + re.escape(end) + r'\n?', re.S)
    return pattern.sub('\n', text)


def top_level_php_override(vhost_text):
    """The vhost's own phpIniOverride lines: outside our section, or preserved inside it."""
    managed = re.search(re.escape(MARK_BEGIN) + r'(.*?)' + re.escape(MARK_END), vhost_text, re.S)
    if managed and PRESERVED in managed.group(1):
        inner = managed.group(1).split(PRESERVED, 1)[1].split(FROM_HTACCESS, 1)[0]
        return [line.strip() for line in inner.splitlines() if line.strip()]
    text = strip_managed(vhost_text)
    depth, lines, capture = 0, [], False
    for line in text.splitlines():
        stripped = line.strip()
        if depth == 0 and re.match(r'^phpIniOverride\s*\{', stripped):
            capture = True
        if capture and depth >= 1 and stripped and stripped != '}':
            lines.append(stripped)
        depth += line.count('{') - line.count('}')
        if capture and depth == 0 and '}' in line:
            capture = False
    return lines


def remove_top_level_php_override(vhost_text):
    """Remove empty-or-duplicated top-level phpIniOverride blocks (we re-emit their lines)."""
    out, depth, skipping = [], 0, False
    for line in vhost_text.splitlines(True):
        stripped = line.strip()
        if depth == 0 and not skipping and re.match(r'^phpIniOverride\s*\{', stripped):
            skipping = True
        if not skipping:
            out.append(line)
        depth += line.count('{') - line.count('}')
        if skipping and depth == 0:
            skipping = False
    return ''.join(out)


def conflicts(vhost_text, result):
    """Top-level blocks outside our section that our output would duplicate."""
    text = strip_managed(vhost_text)
    found = []
    for code in result.vhost['errorpages']:
        if re.search(r'^errorpage\s+%s\b' % code, text, re.M):
            found.append('errorpage %s' % code)
    if result.vhost['expires'] and re.search(r'^expires\s*\{', text, re.M):
        found.append('expires')
    for scope in result.contexts:
        if re.search(r'^context\s+%s\s*\{' % re.escape(scope.uri), text, re.M):
            found.append('context %s' % scope.uri)
    return found


def apply_to_vhost(vhost_text, result):
    """Return the new vhost.conf text with our managed section (and merged phpIniOverride).

    Idempotent: applying the same result twice gives the same text, and applying an empty
    result restores the vhost's original phpIniOverride block.
    """
    managed = re.search(re.escape(MARK_BEGIN) + r'(.*?)' + re.escape(MARK_END), vhost_text, re.S)
    absorbed = bool(managed and PRESERVED in managed.group(1))  # we hold the vhost's own PHP lines
    existing_php = top_level_php_override(vhost_text)
    base = strip_managed(vhost_text)
    merge_php = bool(result.vhost['php']) and _has_output(result)
    if merge_php:
        base = remove_top_level_php_override(base)   # one vhost-level block: ours, with theirs preserved
        block = render_vhost_block(result, existing_php)
    else:
        php_free = Result()
        php_free.vhost, php_free.realms, php_free.contexts = dict(result.vhost, php=[]), result.realms, result.contexts
        block = render_vhost_block(php_free) if _has_output(php_free) else ''
        if absorbed and existing_php:            # give the vhost its PHP lines back
            block = 'phpIniOverride  {\n%s\n}\n\n' % '\n'.join(existing_php) + block
    base = base.rstrip('\n') + '\n'
    match = re.search(r'^vhssl\s*\{', base, re.M)
    if not block:
        text = base
    elif match:  # keep SSL last, as CyberPanel writes it
        text = base[:match.start()] + block + '\n' + base[match.start():]
    else:
        text = base + '\n' + block
    return re.sub(r'\n{3,}', '\n\n', text)


def _has_output(result):
    return bool(result.vhost['php'] or result.vhost['errorpages'] or result.vhost['expires'] or result.realms
                or result.contexts)


def apply_redirects(htaccess_text, lines):
    """Insert (or remove) our managed redirect block at the top of a .htaccess file."""
    text = strip_managed(htaccess_text or '', HT_BEGIN, HT_END).lstrip('\n')
    if not lines:
        return text
    block = '\n'.join([HT_BEGIN, 'RewriteEngine On'] + lines + [HT_END]) + '\n'
    return block + text
