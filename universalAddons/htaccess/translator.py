""".htaccess -> OpenLiteSpeed translator (pure functions, no I/O).

Stock OpenLiteSpeed only honours mod_rewrite rules from .htaccess. This module turns the other
common Apache directives into native OLS vhost configuration:

  php_value / php_flag / php_admin_*      -> phpIniOverride (vhost or context)
  Header / RequestHeader                  -> context extraHeaders
  Order/Allow/Deny, Require ip|all|not ip -> accessControl
  AuthType Basic + AuthUserFile + Require -> realm + context (required user/valid-user)
  ErrorDocument (document root)           -> errorpage
  ExpiresActive / ExpiresByType / Default -> expires
  <Files> / <FilesMatch>                  -> regex contexts (exp:)
  Options +Indexes                        -> autoIndex
  Redirect / RedirectMatch                -> RewriteRule lines (kept in a managed .htaccess block,
                                             which OLS reads natively)
  BruteForce* (same names as CyberPanel's module) -> brute-force guard settings

SECURITY: .htaccess is written by the site owner, but its translation ends up in server
configuration. Every value is therefore validated against a strict character set (no newlines,
braces or heredoc markers), paths must stay inside the site's home, and PHP settings that would
weaken isolation (open_basedir, disable_functions, extension loading...) are refused.
"""
import hashlib
import ipaddress
import re

MARK_BEGIN = '# BEGIN cp-ua-htaccess (generated from .htaccess; do not edit)'
MARK_END = '# END cp-ua-htaccess'
HT_BEGIN = '# BEGIN cp-ua redirects (generated by CyberPanel from Redirect lines; do not edit)'
HT_END = '# END cp-ua redirects'

PHP_NAME_RE = re.compile(r'^[a-z0-9_.]{1,64}$')
PHP_DENY = {
    'open_basedir', 'disable_functions', 'disable_classes', 'enable_dl', 'extension', 'zend_extension',
    'extension_dir', 'allow_url_include', 'sendmail_path', 'mail.force_extra_parameters', 'sys_temp_dir',
    'upload_tmp_dir', 'safe_mode', 'user_ini.filename', 'auto_prepend_file', 'auto_append_file',
    'session.save_path', 'error_log', 'opcache.restrict_api', 'opcache.preload', 'expose_php',
}
SAFE_VALUE_RE = re.compile(r'^[^\x00-\x1f{}\\<>]{0,512}$')           # config-safe value
PATTERN_RE = re.compile(r'^[^\x00-\x20{}"\x7f]{1,200}$')                 # regex: backslashes allowed
HEADER_NAME_RE = re.compile(r'^[A-Za-z0-9!#$%&\'*+.^_`|~-]{1,128}$')
MIME_RE = re.compile(r'^[a-z0-9.+-]+/[a-z0-9.+*-]+$')
URL_PATH_RE = re.compile(r'^(/[A-Za-z0-9._~%!$&\'()*+,;=:@/-]*|https?://[A-Za-z0-9.-]+(:\d+)?(/[A-Za-z0-9._~%!$&\'()*+,;=:@/?-]*)?)$')
REDIRECT_CODES = {'permanent': '301', 'temp': '302', 'seeother': '303', 'gone': '410'}
EXPIRES_UNITS = {'second': 1, 'minute': 60, 'hour': 3600, 'day': 86400, 'week': 604800, 'month': 2592000,
                 'year': 31536000}
NATIVE = {'rewriteengine', 'rewriterule', 'rewritecond', 'rewritebase', 'rewriteoptions', 'rewritemap'}
IGNORED = {'options', 'adddefaultcharset', 'serversignature', 'fileetag', 'setoutputfilter',
           'addoutputfilterbytype', 'addencoding', 'satisfy'}


# ----------------------------------------------------------------------------- parsing

def tokenize(line):
    """Split a directive line on whitespace, honouring double quotes (backslashes are kept)."""
    tokens, current, quoted, had = [], [], False, False
    i = 0
    while i < len(line):
        char = line[i]
        if char == '"':
            quoted = not quoted
            had = True
        elif char.isspace() and not quoted:
            if current or had:
                tokens.append(''.join(current))
            current, had = [], False
        elif char == '\\' and i + 1 < len(line) and line[i + 1] == '"':
            current.append('"')
            i += 1
        else:
            current.append(char)
        i += 1
    if current or had:
        tokens.append(''.join(current))
    return tokens


def parse(text):
    """Return a tree of {'name', 'args', 'line', 'children'} nodes."""
    root = {'name': '', 'args': [], 'line': 0, 'children': []}
    stack = [root]
    pending, start = '', 0
    for number, raw in enumerate((text or '').splitlines(), 1):
        line = raw.strip()
        if pending:
            line = pending + ' ' + line
        else:
            start = number
        if line.endswith('\\'):
            pending = line[:-1].rstrip()
            continue
        pending = ''
        if not line or line.startswith('#'):
            continue
        if line.startswith('</'):
            name = line[2:].rstrip('>').strip().lower()
            if len(stack) > 1 and stack[-1]['name'] == name:
                stack.pop()
            continue
        if line.startswith('<') and line.endswith('>'):
            parts = tokenize(line[1:-1])
            node = {'name': parts[0].lower() if parts else '', 'args': parts[1:], 'line': start, 'children': []}
            stack[-1]['children'].append(node)
            stack.append(node)
            continue
        parts = tokenize(line)
        stack[-1]['children'].append({'name': parts[0].lower(), 'args': parts[1:], 'line': start, 'children': None,
                                      'raw': line})
    return root


# ----------------------------------------------------------------------------- translation

class Scope:
    """Accumulated settings for one URL scope (a directory or a <Files> regex)."""

    def __init__(self, uri, location, is_regex=False):
        self.uri, self.location, self.is_regex = uri, location, is_regex
        self.php, self.headers = [], []
        self.order, self.allow, self.deny, self.require = None, [], [], []
        self.auth = {}
        self.expires_active, self.expires_default, self.expires_by_type = None, None, {}
        self.autoindex = None
        self.index_files = None

    def has_context_settings(self):
        return bool(self.headers or self.access() or self.auth_ready() or self.autoindex is not None
                    or self.index_files or (self.is_regex and self.php) or
                    (self.uri != '/' and (self.php or self.expires_active is not None)))

    def access(self):
        """Return (allow, deny) lists for OLS accessControl, or None when unrestricted."""
        allow, deny = list(self.allow), list(self.deny)
        req_allow = [r for r in self.require if r[0] == 'allow']
        req_deny = [r for r in self.require if r[0] == 'deny']
        if self.require:
            if any(r == ('allow', 'ALL') for r in req_allow):
                return (['ALL'], [r[1] for r in req_deny]) if req_deny else None
            if any(r == ('deny', 'ALL') for r in req_deny) and not req_allow:
                return ([], ['ALL'])
            if req_allow:
                return ([r[1] for r in req_allow], ['ALL'])
            if req_deny:
                return (['ALL'], [r[1] for r in req_deny])
        if not allow and not deny:
            return None
        if self.order == 'allow,deny':      # default deny
            return (['ALL'] if 'ALL' in allow else allow, ['ALL'] if 'ALL' not in allow else
                    [d for d in deny if d != 'ALL'])
        if 'ALL' in deny:                    # deny,allow with "Deny from all": only allows get in
            return (allow, ['ALL'])
        return (['ALL'], deny)

    def auth_ready(self):
        return self.auth.get('type') == 'basic' and self.auth.get('userfile') and self.auth.get('require')


class Result:
    def __init__(self):
        self.report = []
        self.vhost = {'php': [], 'errorpages': {}, 'expires': None}
        self.contexts = []
        self.realms = {}
        self.redirects = {}          # relative dir -> [rewrite lines]
        self.bruteforce = None

    def note(self, path, line, directive, status, detail=''):
        self.report.append({'file': path, 'line': line, 'directive': directive, 'status': status, 'detail': detail})


def _safe(value):
    return isinstance(value, str) and bool(SAFE_VALUE_RE.match(value)) and 'END_' not in value


def _ip(value):
    if value.lower() == 'all':
        return 'ALL'
    try:
        if '/' in value:
            return str(ipaddress.ip_network(value, strict=False))
        return str(ipaddress.ip_address(value))
    except ValueError:
        # Apache partial addresses: "10.1" -> 10.1.0.0/16
        parts = value.rstrip('.').split('.')
        if 1 <= len(parts) < 4 and all(p.isdigit() and int(p) < 256 for p in parts):
            return '%s/%d' % ('.'.join(parts + ['0'] * (4 - len(parts))), 8 * len(parts))
        return None


def _expires(spec):
    """Apache 'access plus 1 month 2 days' / 'A2592000' -> OLS 'A<seconds>' (or None)."""
    spec = spec.strip().strip('"')
    match = re.match(r'^([AM])(\d{1,10})$', spec)
    if match:
        return spec
    words = spec.lower().split()
    if len(words) < 3 or words[0] not in ('access', 'now', 'modification') or words[1] != 'plus':
        return None
    total, rest = 0, words[2:]
    if len(rest) % 2:
        return None
    for count, unit in zip(rest[::2], rest[1::2]):
        if not count.isdigit() or unit.rstrip('s') not in EXPIRES_UNITS:
            return None
        total += int(count) * EXPIRES_UNITS[unit.rstrip('s')]
    return '%s%d' % ('M' if words[0] == 'modification' else 'A', total)


def _redirect_lines(directive, args):
    """Redirect / RedirectMatch -> RewriteRule lines for the document-root .htaccess, or None.

    Redirect matches a URL-path prefix on segment boundaries and appends the rest of the path,
    exactly like mod_alias: "Redirect /old https://x/new" sends /old/a to https://x/new/a.
    """
    status = '302'
    if args and (args[0].lower() in REDIRECT_CODES or args[0].isdigit()):
        status = REDIRECT_CODES.get(args[0].lower(), args[0])
        args = args[1:]
    if status not in ('301', '302', '303', '307', '308', '410') or not args:
        return None
    source = args[0]
    target = '-' if status == '410' else (args[1] if len(args) > 1 else '')
    if target != '-' and (not URL_PATH_RE.match(target) or not _safe(target)):
        return None
    if directive == 'redirect':
        if not re.match(r'^/[A-Za-z0-9._~%/-]*$', source):
            return None
        prefix = re.escape(source.strip('/')).replace('\\/', '/')
        if not prefix:
            pattern, suffix = '^(.*)$', '$1'
        elif source.endswith('/'):
            pattern, suffix = '^%s/(.*)$' % prefix, '$1'
        else:
            pattern, suffix = '^%s(/.*)?$' % prefix, '$1'
        if target != '-':
            target = (target.rstrip('/') + '/' if source.endswith('/') else target) + suffix
    else:
        if not PATTERN_RE.match(source) or not source.lstrip('^').startswith('/'):
            return None
        pattern = '^' + source.lstrip('^')[1:]
    flag = '[G,L]' if status == '410' else '[R=%s,L]' % status
    return ['RewriteRule %s %s %s' % (pattern, target, flag)]


def translate(files, home, docroot):
    """files: {relative_dir: htaccess_text} ('' = document root). Returns a Result.

    home: the site's home directory (AuthUserFile must stay inside it).
    """
    result = Result()
    scopes = {}

    def scope_for(rel):
        if rel not in scopes:
            uri = '/' + rel.strip('/') + '/' if rel.strip('/') else '/'
            scopes[rel] = Scope(uri, '$DOC_ROOT' + uri)
        return scopes[rel]

    for rel in sorted(files):
        path = (rel.strip('/') + '/' if rel.strip('/') else '') + '.htaccess'
        root = parse(files[rel])
        _walk(root['children'], scope_for(rel), rel, path, result, home, scopes, is_root=not rel.strip('/'))
    for rel, scope in sorted(scopes.items()):
        if scope.uri == '/' and not scope.is_regex:
            result.vhost['php'].extend(scope.php)
            if scope.expires_active is not None or scope.expires_by_type:
                result.vhost['expires'] = (scope.expires_active, scope.expires_default, dict(scope.expires_by_type))
        if scope.has_context_settings() or (scope.uri == '/' and scope.headers):
            result.contexts.append(scope)
        if scope.auth_ready():
            realm = 'cpua_' + hashlib.sha1(scope.auth['userfile'].encode()).hexdigest()[:10]
            result.realms[realm] = scope.auth['userfile']
            scope.auth['realm'] = realm
    return result


def _walk(nodes, scope, rel, path, result, home, scopes, is_root, in_files=False):
    for node in nodes:
        name, args, line = node['name'], node['args'], node['line']
        label = (name + ' ' + ' '.join(args)).strip()[:120]
        if node['children'] is not None:
            if name == 'ifmodule':
                negate = args and args[0].startswith('!')
                if negate:
                    result.note(path, line, '<IfModule %s>' % ' '.join(args), 'ignored', 'negated module test')
                    continue
                _walk(node['children'], scope, rel, path, result, home, scopes, is_root, in_files)
            elif name in ('files', 'filesmatch') and not in_files:
                if not args:
                    result.note(path, line, '<%s>' % name, 'unsupported', 'missing pattern')
                    continue
                pattern = args[0].strip('"')
                if name == 'files':
                    if not re.match(r'^[A-Za-z0-9._*?-]+$', pattern):
                        result.note(path, line, '<Files %s>' % pattern, 'unsupported', 'pattern')
                        continue
                    base = re.escape(pattern).replace('\\*', '[^/]*').replace('\\?', '[^/]')
                else:
                    if not PATTERN_RE.match(pattern) or 'END_' in pattern:
                        result.note(path, line, '<FilesMatch>', 'unsupported', 'unsafe pattern')
                        continue
                    # FilesMatch searches the file name (unanchored unless the pattern says so);
                    # confine it to the last path segment.
                    starts = pattern.startswith('^')
                    ends = pattern.endswith('$') and not pattern.endswith('\\$')
                    core = pattern[1 if starts else 0:len(pattern) - (1 if ends else 0)]
                    base = ('' if starts else '[^/]*') + '(?:%s)' % core + ('' if ends else '[^/]*')
                prefix = re.escape(scope.uri if not scope.is_regex else '/').replace('\\/', '/')
                regex = '^%s(.*/)?%s$' % (prefix, base)
                key = 'exp:%s' % regex
                sub = scopes.setdefault(key, Scope('exp:' + regex, None, is_regex=True))
                result.note(path, line, '<%s %s>' % ('Files' if name == 'files' else 'FilesMatch', pattern),
                            'translated', 'context exp:' + regex)
                _walk(node['children'], sub, rel, path, result, home, scopes, is_root, in_files=True)
            else:
                result.note(path, line, '<%s>' % ' '.join([name] + args), 'unsupported', 'section not supported')
            continue
        _directive(name, args, line, label, node.get('raw', ''), scope, rel, path, result, home, is_root, in_files)


def _directive(name, args, line, label, raw, scope, rel, path, result, home, is_root, in_files):
    note = lambda status, detail='': result.note(path, line, label, status, detail)
    if name in NATIVE:
        return note('native', 'OpenLiteSpeed reads rewrite rules from .htaccess itself')
    if name in ('php_value', 'php_flag', 'php_admin_value', 'php_admin_flag'):
        if len(args) < 2 or not PHP_NAME_RE.match(args[0].lower()):
            return note('unsupported', 'malformed')
        setting = args[0].lower()
        if setting in PHP_DENY or setting.startswith('session.save'):
            return note('refused', '%s cannot be changed from .htaccess on this server' % setting)
        value = ' '.join(args[1:])
        if not _safe(value):
            return note('refused', 'value contains characters that are not allowed')
        kind = 'php_flag' if name.endswith('flag') else 'php_value'
        if kind == 'php_flag' and value.lower() not in ('on', 'off', '1', '0', 'true', 'false'):
            return note('unsupported', 'php_flag expects on/off')
        scope.php.append('%s %s %s' % (kind, setting, value if ' ' not in value else '"%s"' % value.replace('"', '')))
        return note('translated', 'phpIniOverride')
    if name in ('header', 'requestheader'):
        words = list(args)
        if words and words[0].lower() in ('always', 'onsuccess'):
            words = words[1:]
        if len(words) < 2 or words[0].lower() not in ('set', 'append', 'merge', 'add', 'unset'):
            return note('unsupported', 'only set/append/merge/add/unset are supported')
        action, header = words[0].lower(), words[1]
        value = ' '.join(words[2:])
        if not HEADER_NAME_RE.match(header) or (action != 'unset' and not value) or not _safe(value):
            return note('refused', 'invalid header name or value')
        if 'env=' in value:
            return note('unsupported', 'conditional headers (env=) are not supported')
        scope.headers.append('%s %s %s%s' % ('Header' if name == 'header' else 'RequestHeader', action, header,
                                             (' "%s"' % value.replace('"', "'")) if value else ''))
        return note('translated', 'extraHeaders')
    if name == 'order':
        value = ''.join(args).lower().replace(' ', '')
        if value not in ('allow,deny', 'deny,allow'):
            return note('unsupported', 'Order must be allow,deny or deny,allow')
        scope.order = value
        return note('translated', 'accessControl')
    if name in ('allow', 'deny'):
        if not args or args[0].lower() != 'from':
            return note('unsupported', 'expected "%s from ..."' % name)
        bad = []
        for value in args[1:]:
            ip = _ip(value)
            if ip is None:
                bad.append(value)
            else:
                (scope.allow if name == 'allow' else scope.deny).append(ip)
        return note('translated' if not bad else 'partial', 'accessControl' +
                    ('; host names are not supported: ' + ', '.join(bad) if bad else ''))
    if name == 'require':
        words = [a.lower() for a in args]
        if words[:2] == ['all', 'granted']:
            scope.require.append(('allow', 'ALL'))
        elif words[:2] == ['all', 'denied']:
            scope.require.append(('deny', 'ALL'))
        elif words[:1] == ['ip'] or words[:2] == ['not', 'ip']:
            negate = words[0] == 'not'
            values = args[2:] if negate else args[1:]
            ips = [_ip(v) for v in values]
            if not ips or None in ips:
                return note('unsupported', 'invalid address')
            scope.require.extend(('deny' if negate else 'allow', ip) for ip in ips)
        elif words[:1] in (['valid-user'], ['user']):
            users = args[1:] if words[0] == 'user' else []
            if any(not re.match(r'^[A-Za-z0-9._@-]{1,64}$', u) for u in users):
                return note('refused', 'invalid user name')
            scope.auth['require'] = 'valid-user' if words[0] == 'valid-user' else 'user ' + ' '.join(users)
            return note('translated', 'realm')
        else:
            return note('unsupported', 'Require form not supported')
        return note('translated', 'accessControl')
    if name == 'authtype':
        if args and args[0].lower() == 'basic':
            scope.auth['type'] = 'basic'
            return note('translated', 'realm')
        return note('unsupported', 'only Basic authentication is supported')
    if name == 'authname':
        value = ' '.join(args)
        if not _safe(value):
            return note('refused', 'invalid AuthName')
        scope.auth['name'] = value
        return note('translated', 'realm')
    if name == 'authuserfile':
        target = args[0] if args else ''
        normal = re.sub(r'/+', '/', target)
        if not normal.startswith(home.rstrip('/') + '/') or '..' in normal.split('/') or not _safe(normal) \
                or ' ' in normal:
            return note('refused', 'AuthUserFile must be inside %s' % home)
        scope.auth['userfile'] = normal
        return note('translated', 'realm')
    if name == 'errordocument':
        if not is_root or in_files:
            return note('unsupported', 'ErrorDocument is supported in the document-root .htaccess only')
        if len(args) < 2 or not args[0].isdigit() or not 400 <= int(args[0]) <= 599:
            return note('unsupported', 'malformed')
        target = args[1]
        if not URL_PATH_RE.match(target) or not _safe(target):
            return note('unsupported', 'only URLs or local paths are supported (not inline text)')
        result.vhost['errorpages'][args[0]] = target
        return note('translated', 'errorpage')
    if name == 'expiresactive':
        scope.expires_active = bool(args) and args[0].lower() == 'on'
        return note('translated', 'expires')
    if name in ('expiresbytype', 'expiresdefault'):
        if name == 'expiresbytype':
            if len(args) < 2 or not MIME_RE.match(args[0].lower()):
                return note('unsupported', 'malformed')
            value = _expires(' '.join(args[1:]))
        else:
            value = _expires(' '.join(args))
        if not value:
            return note('unsupported', 'unrecognised expiry time')
        if name == 'expiresbytype':
            scope.expires_by_type[args[0].lower()] = value
        else:
            scope.expires_default = value
        return note('translated', 'expires')
    if name == 'options':
        words = [a.lower() for a in args]
        if '+indexes' in words or 'indexes' in words:
            scope.autoindex = True
            return note('translated', 'autoIndex')
        if '-indexes' in words:
            return note('native', 'directory listing is already off in OpenLiteSpeed')
        return note('ignored', 'no OpenLiteSpeed equivalent needed')
    if name == 'directoryindex':
        files = [a for a in args if re.match(r'^[A-Za-z0-9._-]{1,64}$', a)]
        if not files or len(files) != len(args):
            return note('unsupported', 'malformed')
        if is_root and not in_files:
            return note('unsupported', 'set index files for the whole site in the panel (vhost index)')
        scope.index_files = files
        return note('translated', 'indexFiles')
    if name in ('redirect', 'redirectmatch', 'redirectpermanent', 'redirecttemp'):
        directive = 'redirectmatch' if name == 'redirectmatch' else 'redirect'
        extra = ['301'] if name == 'redirectpermanent' else (['302'] if name == 'redirecttemp' else [])
        lines = _redirect_lines(directive, extra + list(args))
        if not lines or in_files:
            return note('unsupported', 'malformed or unsupported redirect')
        result.redirects.setdefault('', []).extend(lines)  # URL paths are absolute: document root
        return note('translated', 'RewriteRule in the managed .htaccess block')
    if name.startswith('bruteforce'):
        return _bruteforce(name, args, note, result)
    if name in IGNORED:
        return note('ignored', 'no OpenLiteSpeed equivalent needed')
    return note('unsupported', 'not supported by the translator')


def _bruteforce(name, args, note, result):
    config = result.bruteforce or {'enabled': False, 'attempts': 10, 'window': 300, 'action': 'block',
                                   'whitelist': [], 'paths': ['/wp-login.php', '/xmlrpc.php'], 'xff': False}
    value = args[0] if args else ''
    if name == 'bruteforceprotection':
        config['enabled'] = value.lower() == 'on'
    elif name in ('bruteforceallowedattempts', 'bruteforceattempts') and value.isdigit() and 1 <= int(value) <= 1000:
        config['attempts'] = int(value)
    elif name == 'bruteforcewindow' and value.isdigit() and 10 <= int(value) <= 86400:
        config['window'] = int(value)
    elif name == 'bruteforceaction' and value.lower() in ('block', 'log', 'throttle'):
        config['action'] = value.lower()
    elif name == 'bruteforcewhitelist':
        ips = [_ip(a) for a in args]
        if None in ips or not ips:
            return note('unsupported', 'invalid address in whitelist')
        config['whitelist'].extend(ips)
    elif name == 'bruteforceprotectpath' and value.startswith('/') and re.match(r'^[A-Za-z0-9._~/-]{1,200}$', value):
        if config['paths'] == ['/wp-login.php', '/xmlrpc.php']:
            config['paths'] = []
        config['paths'].append(value)
    elif name == 'bruteforcexforwardedfor':
        config['xff'] = value.lower() == 'on'
    else:
        return note('unsupported', 'invalid value')
    result.bruteforce = config
    return note('translated', 'brute-force guard')


